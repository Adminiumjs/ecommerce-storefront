/**
 * Chrome strings — the app shell (`app/App.tsx`), every shared component in
 * `components/`, the zustand store's toast copy, and the `lib/` layer's labels.
 *
 * `en-US` is the source of truth: `MessageKey` is derived from it (see
 * ../messages/index.ts), so a typo in a `t('…')` call is a compile error, and
 * the parity guard there fails the build if a translation drops a key.
 *
 * `satisfies` — not a type annotation — is load-bearing. Annotating this
 * `Record<LocaleTag, Record<string, string>>` widens the key type to `string`
 * and `MessageKey` with it, silently turning every typo back into a runtime
 * miss. Add keys, never the annotation.
 *
 * Plurals use the `|` convention documented in ../index.tsx: variants in the
 * locale's own CLDR category order (en/de/fr/da: one|other · cs: one|few|other ·
 * zh-CN/zh-TW: a single variant, no `|` · ar: zero|one|two|few|many|other).
 *
 * Scope: UI chrome only. Northline's own catalogue content — product titles,
 * option labels, spec rows, seeded review bodies — is demo fiction and stays
 * English, the way a real storefront shows whatever the merchant typed in.
 *
 * Two conventions worth knowing before adding keys here:
 *
 *   · Numbers never appear literally in a message. `{pct}`, `{count}`, `{price}`
 *     and friends are always substituted with a string the caller produced
 *     through the runtime's `number` / `money` / `date` helpers, so "15% off"
 *     reads "‎15 %" in fr-FR and "١٥٪" in ar-EG without the translator doing
 *     anything. For a plural message the caller passes the RAW count as `t`'s
 *     third argument (that selects the variant) and the FORMATTED count as a
 *     `{count}` param (that is what renders).
 *
 *   · fr-FR carries a NO-BREAK SPACE before `? ! : ;` and inside guillemets.
 *     It is written ` ` rather than pasted, because an invisible character
 *     in a diff is a character nobody can review.
 */
